#!/usr/bin/env python3
"""Write public/img/{key}-{480,960,1920}.webp from a folder of originals and regenerate config/photos.php.

Usage: python3 scripts/photos.py /path/to/originals   (files named <key>.jpg / .png)

Each width is capped at the original's width, so small originals (the centre's own photos
from its Google Site are 200-730px wide) are never blown up; sizes that would only repeat
the original are skipped. Requires Pillow with WebP support.
"""
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'img')
WIDTHS = [480, 960, 1920]


def main(src: str) -> None:
    os.makedirs(OUT, exist_ok=True)
    meta = {}
    for name in sorted(os.listdir(src)):
        key, ext = os.path.splitext(name)
        if ext.lower() not in ('.jpg', '.jpeg', '.png') or key.startswith('logo'):
            continue
        im = ImageOps.exif_transpose(Image.open(os.path.join(src, name))).convert('RGB')
        w, h = im.size
        sizes = []
        for target in WIDTHS:
            if sizes and sizes[-1][1] >= w:
                break  # the previous size is already the full original
            tw = min(target, w)
            th = round(h * tw / w)
            im.resize((tw, th), Image.LANCZOS).save(os.path.join(OUT, f'{key}-{target}.webp'), 'WEBP', quality=78, method=6)
            sizes.append((target, tw))
        meta[key] = {'w': min(w, 1920), 'h': round(h * min(w, 1920) / w), 'sizes': [s for s, _ in sizes]}
        print(f'{key}: {w}x{h} -> {[s for s, _ in sizes]}')
    lines = ['<?php', '', '// Generated by scripts/photos.py: the size of each photo in public/img and the widths written.', 'return [']
    for key, m in meta.items():
        lines.append(f"    '{key}' => ['w' => {m['w']}, 'h' => {m['h']}, 'sizes' => [{', '.join(map(str, m['sizes']))}]],")
    lines.append('];')
    with open(os.path.join(ROOT, 'config', 'photos.php'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
